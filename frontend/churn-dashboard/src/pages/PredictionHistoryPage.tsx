import {
  Alert,
  Box,
  Button,
  Chip,
  CircularProgress,
  MenuItem,
  Paper,
  Select,
  Stack,
  Table,
  TableBody,
  TableCell,
  TableContainer,
  TableHead,
  TableRow,
  Typography,
} from "@mui/material";

import RefreshIcon
  from "@mui/icons-material/Refresh";

import {
  useMemo,
  useState,
} from "react";

import {
  usePredictionHistory,
} from "../hooks/usePredictionHistory";


type PredictionFilter =
  | "all"
  | "churn"
  | "no-churn";


export default function PredictionHistoryPage() {


  // Filter

  const [
    predictionFilter,
    setPredictionFilter,
  ] = useState<
    PredictionFilter
  >(
    "all"
  );



  // Query

  const historyQuery =
    usePredictionHistory(
      100
    );


  // Filtered Data

  const filteredItems =
    useMemo(
      () => {

        const items =
          historyQuery
            .data
            ?.items
          ?? [];


        if (
          predictionFilter
          === "churn"
        ) {

          return items.filter(
            item =>
              item.prediction
              === 1
          );
        }


        if (
          predictionFilter
          === "no-churn"
        ) {

          return items.filter(
            item =>
              item.prediction
              === 0
          );
        }


        return items;

      },

      [
        historyQuery.data,
        predictionFilter,
      ]
    );


  
  // Loading
 
  if (
    historyQuery.isLoading
  ) {

    return (
      <Box
        sx={{
          display: "flex",
          justifyContent: "center",
          alignItems: "center",
          minHeight: 300,
        }}
      >

        <CircularProgress />

      </Box>
    );
  }



  // Error

  if (
    historyQuery.isError
  ) {

    return (
      <Alert
        severity="error"
        action={

          <Button
            color="inherit"
            size="small"
            startIcon={
              <RefreshIcon />
            }
            onClick={() => {
              void historyQuery
                .refetch();
            }}
          >
            Retry
          </Button>

        }
      >
        Failed to load
        prediction history.
      </Alert>
    );
  }


  
  // Page

  return (

    <Stack spacing={3}>

      {/* Header */}

      <Box>

        <Typography
          variant="h4"
          sx={{
            fontWeight: 700,
          }}
        >
          Prediction History
        </Typography>


        <Typography
          color="text.secondary"
          sx={{
            mt: 0.5,
          }}
        >
          Recent customer churn
          predictions generated by
          the production model.
        </Typography>

      </Box>


      {/* Summary + Filter */}

      <Stack

        direction={{
          xs: "column",
          sm: "row",
        }}

        sx={{justifyContent: "space-between",
        spacing:2,
        alignItems:{
            xs: "stretch",
            sm: "center",
            }
        }}
      >

        <Typography
          variant="body2"
          color="text.secondary"
        >
          Showing{" "}
          {
            filteredItems.length
          }
          {" "}
          of{" "}
          {
            historyQuery
              .data
              ?.total
            ?? 0
          }
          {" "}
          predictions
        </Typography>


        <Select
          size="small"

          value={
            predictionFilter
          }

          onChange={
            event =>
              setPredictionFilter(
                event.target.value as PredictionFilter
              )
          }

          sx={{
            minWidth: 190,
          }}
        >

          <MenuItem
            value="all"
          >
            All predictions
          </MenuItem>


          <MenuItem
            value="churn"
          >
            Churn
          </MenuItem>


          <MenuItem
            value="no-churn"
          >
            No Churn
          </MenuItem>

        </Select>

      </Stack>


      {/* Empty State */}

      {
        filteredItems.length
        === 0
        ? (

          <Paper
            sx={{
              p: 5,
              borderRadius: 3,
              textAlign: "center",
            }}
          >

            <Typography
              variant="h6"
              sx={{
                fontWeight: 600,
              }}
            >
              No prediction history
            </Typography>


            <Typography
              variant="body2"
              color="text.secondary"
              sx={{
                mt: 1,
              }}
            >
              Run a customer prediction
              to create the first
              history record.
            </Typography>

          </Paper>

        )
        : (

          <TableContainer
            component={Paper}

            sx={{
              borderRadius: 3,
              overflowX: "auto",
            }}
          >

            <Table
              sx={{
                minWidth: 850,
              }}
            >

              <TableHead>

                <TableRow>

                  <TableCell>
                    Timestamp
                  </TableCell>

                  <TableCell>
                    Customer
                  </TableCell>

                  <TableCell>
                    Prediction
                  </TableCell>

                  <TableCell
                    align="right"
                  >
                    Probability
                  </TableCell>

                  <TableCell
                    align="right"
                  >
                    Threshold
                  </TableCell>

                  <TableCell>
                    Risk
                  </TableCell>

                </TableRow>

              </TableHead>


              <TableBody>

                {filteredItems.map(
                  item => (

                    <TableRow
                      key={
                        item.id
                      }
                      hover
                    >

                      <TableCell>
                        {
                          new Date(
                            item.timestamp
                          )
                          .toLocaleString()
                        }
                      </TableCell>


                      <TableCell>
                        {
                          item.customer_id
                          ?? "-"
                        }
                      </TableCell>


                      <TableCell>

                        <Chip
                          size="small"

                          label={
                            item.prediction_label
                          }

                          color={
                            item.prediction
                            === 1
                              ? "warning"
                              : "success"
                          }

                          variant="outlined"
                        />

                      </TableCell>


                      <TableCell
                        align="right"
                      >
                        {
                          (
                            item
                              .churn_probability
                            * 100
                          )
                          .toFixed(1)
                        }
                        %
                      </TableCell>


                      <TableCell
                        align="right"
                      >
                        {
                          item
                            .threshold
                            .toFixed(2)
                        }
                      </TableCell>


                      <TableCell>

                        <Chip
                          size="small"

                          label={
                            item.risk_level
                            ?? "-"
                          }

                          variant="outlined"
                        />

                      </TableCell>

                    </TableRow>

                  )
                )}

              </TableBody>

            </Table>

          </TableContainer>

        )
      }

    </Stack>
  );
}